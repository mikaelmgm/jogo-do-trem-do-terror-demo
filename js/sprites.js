const _txtCache = {};
function textCanvas(str, color, shadow) {
  const s = String(str).normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase();
  const key = s + '|' + color + '|' + shadow;
  if (_txtCache[key]) return _txtCache[key];
  const c = document.createElement('canvas');
  c.width = Math.max(1, s.length * 4 - 1 + (shadow ? 1 : 0));
  c.height = 5 + (shadow ? 1 : 0);
  const x = c.getContext('2d');
  const paint = (col, ox, oy) => {
    x.fillStyle = col;
    for (let i = 0; i < s.length; i++) {
      const gl = FONT[s[i]] || FONT['?'];
      for (let r = 0; r < 5; r++) for (let q = 0; q < 3; q++) if (gl[r][q] === '#') x.fillRect(i * 4 + q + ox, r + oy, 1, 1);
    }
  };
  if (shadow) paint(shadow, 1, 1);
  paint(color, 0, 0);
  _txtCache[key] = c;
  return c;
}

function drawText(ctx, str, x, y, color, align, shadow) {
  const c = textCanvas(str, color || '#fff', shadow === undefined ? '#07050d' : shadow);
  let dx = x;
  if (align === 'center') dx = x - Math.floor(c.width / 2);
  else if (align === 'right') dx = x - c.width;
  ctx.drawImage(c, Math.round(dx), Math.round(y));
  return c.width;
}

const BAYER4 = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5].map(v => (v + 0.5) / 16);
const bayer = (x, y) => BAYER4[(y & 3) * 4 + (x & 3)];

// halo pontilhado (luz de abóbora, janelas, lua)
function makeGlow(r, color) {
  const c = document.createElement('canvas');
  c.width = c.height = r * 2 + 1;
  const x = c.getContext('2d');
  x.fillStyle = color;
  for (let j = -r; j <= r; j++) for (let i = -r; i <= r; i++) {
    const d = Math.sqrt(i * i + j * j) / r;
    if (d <= 1 && (1 - d) * 0.9 > bayer(i + r, j + r)) x.fillRect(i + r, j + r, 1, 1);
  }
  return c;
}

function makeEllipse(rx, ry, color) {
  const c = document.createElement('canvas');
  c.width = rx * 2 + 1; c.height = ry * 2 + 1;
  const x = c.getContext('2d');
  x.fillStyle = color;
  for (let j = -ry; j <= ry; j++) for (let i = -rx; i <= rx; i++)
    if ((i * i) / (rx * rx) + (j * j) / (ry * ry) <= 1) x.fillRect(i + rx, j + ry, 1, 1);
  return c;
}

function mulberry32(a) {
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
